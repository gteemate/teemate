create policy "members read" on public.members for select to authenticated using (public.current_member_id() is not null);
revoke all on public.members from authenticated;
grant select (id, name, gui, hcp_index, committee) on public.members to authenticated;

-- Your own buddies.
create policy "own buddies" on public.buddies for select to authenticated using (member_id = public.current_member_id());
create policy "add own buddies" on public.buddies for insert to authenticated with check (member_id = public.current_member_id());
create policy "remove own buddies" on public.buddies for delete to authenticated using (member_id = public.current_member_id());

-- Your own bookings (ones you made or are playing in). Writes only via book_tee_time().
-- The helper runs without RLS so the two policies don't refer to each other in a loop.
create function public.my_booking_ids() returns setof bigint
language sql stable security definer set search_path = '' as $$
  select id from public.bookings where booked_by = public.current_member_id()
  union
  select booking_id from public.booking_players where member_id = public.current_member_id()
$$;
create policy "own bookings" on public.bookings for select to authenticated
  using (id in (select public.my_booking_ids()));
create policy "own booking players" on public.booking_players for select to authenticated
  using (booking_id in (select public.my_booking_ids()));
revoke insert, update, delete on public.bookings, public.booking_players, public.guest_visits, public.tee_slots from authenticated;

-- Guest points: your own; the committee sees everyone's.
create policy "own or committee" on public.guest_visits for select to authenticated
  using (member_id = public.current_member_id() or public.is_committee());

-- Committee edits pins, games and events.
create policy "committee writes" on public.pin_sheets    for all to authenticated using (public.is_committee()) with check (public.is_committee());
create policy "committee writes" on public.game_settings for all to authenticated using (public.is_committee()) with check (public.is_committee());
create policy "committee writes" on public.game_prefs    for all to authenticated using (public.is_committee()) with check (public.is_committee());
create policy "committee writes" on public.events        for all to authenticated using (public.is_committee()) with check (public.is_committee());

-- Rounds: you can start and update your own cards.
create policy "own rounds insert" on public.rounds for insert to authenticated with check (created_by = public.current_member_id());
create policy "own rounds update" on public.rounds for update to authenticated
  using (created_by = public.current_member_id()) with check (created_by = public.current_member_id());

-- ---------------------------------------------------------------- functions the app calls

-- Tee sheet for a day, with who's booked on each time.
-- Times for the next 14 days are created the first time someone looks at that day.
create function public.get_tee_sheet(p_date date) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_course bigint := (select id from public.courses order by id limit 1);
begin
  if public.current_member_id() is null then
    raise exception 'Only members can see the tee sheet.' using errcode = '42501';
  end if;
  if p_date between current_date and current_date + 13 then
    insert into public.tee_slots (course_id, date, start_time, twilight)
    select v_course, p_date, m, m >= 15 * 60
      from generate_series(7 * 60 + 30, 16 * 60 + 30, 10) m
     where not (m >= 12 * 60 + 20 and m < 13 * 60)          -- held for the Ladies' Comp
    on conflict do nothing;
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', s.id, 'date', s.date, 'time', s.start_time, 'capacity', s.capacity, 'twilight', s.twilight,
             'players', coalesce((
               select jsonb_agg(jsonb_build_object('name', coalesce(m.name, bp.guest_name), 'memberId', bp.member_id, 'guest', bp.member_id is null) order by bp.id)
                 from public.booking_players bp left join public.members m on m.id = bp.member_id
                where bp.slot_id = s.id), '[]'::jsonb))
           order by s.start_time)
      from public.tee_slots s
     where s.course_id = v_course and s.date = p_date), '[]'::jsonb);
end $$;

-- Book a tee time for me, plus other members and guests, in one transaction.
-- The tee time row is locked, so two people booking the last spaces at once are handled
-- one after the other; the second sees the spaces gone. My member row is locked while
-- guest points are checked, so two bookings at once can't both spend the same points.
create function public.book_tee_time(p_slot_id bigint, p_member_ids bigint[] default '{}', p_guests jsonb default '[]')
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me bigint := public.current_member_id();
  v_slot public.tee_slots;
  v_ids bigint[];
  v_guests int := jsonb_array_length(coalesce(p_guests, '[]'));
  v_taken int;
  v_cost int := 0;
  v_used int;
  v_booking bigint;
  g jsonb;
  v_bp bigint;
begin
  if v_me is null then
    raise exception 'Only members can book tee times.' using errcode = '42501';
  end if;

  select * into v_slot from public.tee_slots where id = p_slot_id for update;
  if not found then
    raise exception 'That tee time no longer exists.' using errcode = 'P0001';
  end if;
  if v_slot.date < current_date then
    raise exception 'That tee time has passed.' using errcode = 'P0001';
  end if;

  v_ids := array[v_me] || coalesce(p_member_ids, '{}');
  if (select count(distinct x) from unnest(v_ids) x) <> cardinality(v_ids) then
    raise exception 'A player is listed twice.' using errcode = 'P0001';
  end if;
  if (select count(*) from public.members where id = any(v_ids)) <> cardinality(v_ids) then
    raise exception 'One of those players isn''t a member.' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.booking_players where slot_id = v_slot.id and member_id = any(v_ids)) then
    raise exception 'One of your group is already booked on this time.' using errcode = 'P0001';
  end if;

  for g in select * from jsonb_array_elements(coalesce(p_guests, '[]')) loop
    if coalesce(trim(g->>'name'), '') = '' then
      raise exception 'Every guest needs a name.' using errcode = 'P0001';
    end if;
    if coalesce(g->>'gui', '') <> '' and (g->>'gui') !~ '^\d{6,10}$' then
      raise exception 'GUI numbers are 6–10 digits.' using errcode = 'P0001';
    end if;
  end loop;

  select count(*) into v_taken from public.booking_players where slot_id = v_slot.id;
  if cardinality(v_ids) + v_guests > v_slot.capacity - v_taken then
    raise exception 'Sorry, those spaces have just been taken. Pick another time.' using errcode = 'P0001';
  end if;

  if v_guests > 0 then
    perform 1 from public.members where id = v_me for update;
    v_cost := (select guest_points from public.courses where id = v_slot.course_id);
    select coalesce(sum(points), 0) into v_used from public.guest_visits
     where member_id = v_me and date_trunc('year', date) = date_trunc('year', v_slot.date::timestamp);
    if v_used + v_cost * v_guests > (select guest_allowance from public.club_settings where id = 1) then
      raise exception 'You don''t have enough guest points for this booking.' using errcode = 'P0001';
    end if;
  end if;

  insert into public.bookings (slot_id, booked_by) values (v_slot.id, v_me) returning id into v_booking;
  insert into public.booking_players (booking_id, slot_id, member_id)
    select v_booking, v_slot.id, x from unnest(v_ids) with ordinality u(x, o) order by o;
  for g in select * from jsonb_array_elements(coalesce(p_guests, '[]')) loop
    insert into public.booking_players (booking_id, slot_id, guest_name, guest_club, guest_gui)
      values (v_booking, v_slot.id, trim(g->>'name'), nullif(trim(g->>'club'), ''), nullif(g->>'gui', ''))
      returning id into v_bp;
    insert into public.guest_visits (member_id, booking_player_id, date, guest_name, guest_club, course_id, points)
      values (v_me, v_bp, v_slot.date, trim(g->>'name'), nullif(trim(g->>'club'), ''), v_slot.course_id, v_cost);
  end loop;

  return jsonb_build_object(
    'id', v_booking, 'date', v_slot.date, 'time', v_slot.start_time,
    'guests', v_guests, 'pointsUsed', v_cost * v_guests,
    'players', (select jsonb_agg(coalesce(m.name, bp.guest_name || ' (guest)') order by bp.id)
                  from public.booking_players bp left join public.members m on m.id = bp.member_id
                 where bp.booking_id = v_booking));
end $$;

-- My upcoming bookings, with everyone in each booking.
create function public.get_my_bookings() returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', b.id, 'date', s.date, 'time', s.start_time,
           'players', (select jsonb_agg(coalesce(m.name, bp.guest_name || ' (guest)') order by bp.id)
                         from public.booking_players bp left join public.members m on m.id = bp.member_id
                        where bp.booking_id = b.id))
         order by s.date, s.start_time), '[]'::jsonb)
    from public.bookings b join public.tee_slots s on s.id = b.slot_id
   where s.date >= current_date
     and (b.booked_by = public.current_member_id()
          or exists (select 1 from public.booking_players bp where bp.booking_id = b.id and bp.member_id = public.current_member_id()))
$$;

-- Make one event the active one (only one can be).
create function public.set_active_event(p_event_id bigint, p_active boolean) returns void
language plpgsql security invoker set search_path = '' as $$
begin
  if p_active then
    update public.events set active = false where active and id <> p_event_id;
  end if;
  update public.events set active = p_active where id = p_event_id;
end $$;

-- Only signed-in users can call the functions; each one checks membership itself.
revoke execute on all functions in schema public from public, anon;
grant execute on function public.current_member_id(), public.is_committee(), public.my_booking_ids(), public.get_tee_sheet(date),
  public.book_tee_time(bigint, bigint[], jsonb), public.get_my_bookings(), public.set_active_event(bigint, boolean)
  to authenticated;
