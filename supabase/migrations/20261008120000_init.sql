-- TeeMates schema: tables, Row Level Security, and the functions the app calls.
--
-- Security model
--   * Only signed-in users who are on the members list can see anything (anon sees nothing).
--   * A login is linked to a member by email (see link_member_to_user).
--   * Committee members can edit pins, games and events.
--   * Bookings and guest points can only be written through book_tee_time(), which checks
--     spaces and points in one transaction, so double bookings and negative balances can't happen.

-- ---------------------------------------------------------------- club and course

create table public.club_settings (
  id int primary key default 1 check (id = 1),          -- single row
  guest_allowance int not null default 36 check (guest_allowance >= 0)
);

create table public.courses (
  id bigint generated by default as identity primary key,
  name text not null unique,
  guest_points int not null default 3 check (guest_points >= 0)   -- points a guest costs on this course
);

create table public.tees (
  course_id bigint not null references public.courses on delete cascade,
  key text not null,
  name text not null,
  colour text not null,
  rating numeric(4,1),
  slope int,
  sort int not null default 0,
  primary key (course_id, key)
);

create table public.holes (
  course_id bigint not null references public.courses on delete cascade,
  n int not null check (n between 1 and 18),
  name text not null,
  par int not null check (par between 3 and 6),
  si int not null check (si between 1 and 18),
  green_depth int not null,
  yards jsonb not null,                                   -- { "black": 441, "white": 402, ... }
  primary key (course_id, n),
  unique (course_id, si)
);

-- ---------------------------------------------------------------- members

create table public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  gui text unique,                                        -- Golf Ireland number
  hcp_index numeric(4,1) not null default 54,
  committee boolean not null default false,
  email text unique check (email = lower(email)),         -- used to link a login; never sent to other members
  user_id uuid unique references auth.users on delete set null
);

create table public.buddies (
  member_id bigint not null references public.members on delete cascade,
  buddy_id bigint not null references public.members on delete cascade,
  primary key (member_id, buddy_id),
  check (member_id <> buddy_id)
);

-- The signed-in user's member id (null if they're not on the members list).
create function public.current_member_id() returns bigint
language sql stable security definer set search_path = '' as $$
  select id from public.members where user_id = auth.uid()
$$;

create function public.is_committee() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select committee from public.members where user_id = auth.uid()), false)
$$;

-- Link a new login to the member with the same email.
create function public.link_member_to_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.members set user_id = new.id
   where email = lower(new.email) and user_id is null;
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.link_member_to_user();

-- ---------------------------------------------------------------- pins

create table public.pin_sheets (
  course_id bigint not null references public.courses on delete cascade,
  date date not null,
  set_at timestamptz not null default now(),
  set_by bigint references public.members on delete set null,
  pins jsonb not null,                                    -- [{ "hole": 1, "yardsOn": 8, "side": "L" }, ...]
  primary key (course_id, date)
);

-- ---------------------------------------------------------------- tee times, bookings, guest points

create table public.tee_slots (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses on delete cascade,
  date date not null,
  start_time smallint not null check (start_time between 0 and 1439),   -- minutes after midnight
  capacity smallint not null default 4 check (capacity between 1 and 4),
  twilight boolean not null default false,
  unique (course_id, date, start_time)
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  slot_id bigint not null references public.tee_slots on delete cascade,
  booked_by bigint not null references public.members on delete cascade,
  created_at timestamptz not null default now()
);

create table public.booking_players (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings on delete cascade,
  slot_id bigint not null references public.tee_slots on delete cascade,
  member_id bigint references public.members on delete cascade,      -- null for a guest
  guest_name text,
  guest_club text,
  guest_gui text,
  check ((member_id is null) <> (guest_name is null)),
  unique (slot_id, member_id)                                        -- a member can't be on one tee time twice
);
create index on public.booking_players (booking_id);

-- Guest points ledger: one row per guest brought, charged to the host member.
create table public.guest_visits (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members on delete cascade,
  booking_player_id bigint references public.booking_players on delete set null,
  date date not null,
  guest_name text not null,
  guest_club text,
  course_id bigint not null references public.courses,
  points int not null check (points >= 0)
);
create index on public.guest_visits (member_id, date);

-- Backstop: a member's points used in a year can never exceed the allowance,
-- however a row got there.
create function public.check_guest_balance() returns trigger
language plpgsql set search_path = '' as $$
declare
  used int;
  allowance int := (select guest_allowance from public.club_settings where id = 1);
begin
  select coalesce(sum(points), 0) into used from public.guest_visits
   where member_id = new.member_id and date_trunc('year', date) = date_trunc('year', new.date);
  if used > allowance then
    raise exception 'You don''t have enough guest points for this booking.' using errcode = 'P0001';
  end if;
  return null;
end $$;

create constraint trigger guest_balance_never_negative
  after insert or update on public.guest_visits
  for each row execute function public.check_guest_balance();

-- ---------------------------------------------------------------- games, rounds, events

create table public.game_settings (
  game_key text primary key,
  enabled boolean not null default true,
  allowance_pct int check (allowance_pct between 0 and 100)
);

create table public.game_prefs (
  group_size int primary key check (group_size between 2 and 4),
  game_key text not null
);

create table public.rounds (
  id bigint generated by default as identity primary key,
  date date not null default current_date,
  created_by bigint not null default public.current_member_id() references public.members on delete cascade,
  players bigint[] not null,                    -- member ids in card order; players[1] is the creator
  game text,
  pairing int not null default 0 check (pairing between 0 and 2),
  scores jsonb not null default '[]',           -- gross per hole per player: [[4,5,4,4], ...]
  done jsonb not null default '[]',             -- [true, true, false, ...]
  submitted jsonb not null default '{}',
  tee_time text,                                -- shown on the leaderboard before they start
  updated_at timestamptz not null default now()
);
create index on public.rounds (date);

create table public.events (
  id bigint generated by default as identity primary key,
  name text not null,
  team_a jsonb not null,                        -- { "name": "Blues", "col": "#19335A" }
  team_b jsonb not null,
  active boolean not null default false,
  days int not null default 1 check (days between 1 and 3),
  course text not null,
  format text not null,
  players bigint[] not null default '{}',
  team jsonb not null default '{}',             -- { "<member id>": "A" | "B" }
  matches jsonb not null default '{}'           -- { "1": [{ a, b, tee, res }], ... }
);
create unique index one_active_event on public.events (active) where active;

